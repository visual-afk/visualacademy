-- ── 강사 ──
create table if not exists instructors (
  id text primary key,
  initial text not null,
  name text not null,
  role text not null default '',
  "desc" text not null default '',
  sort_order int not null default 0
);

-- ── 클래스 (src/lib/types.ts AcademyClass) ──
create table if not exists classes (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  cat text not null check (cat in ('정석','특강','세미나','경영','온라인')),
  field text not null,
  target text not null,
  type text not null check (type in ('offline','seminar','waitlist','online','upcoming')),
  day text,
  time text,
  place text,
  date date,
  capacity int,
  -- 아임웹 이관분·현장 등록 등 주문 테이블 밖의 신청 인원. 실제 applied 는 view 에서 주문 수를 더해 계산
  applied_base int not null default 0,
  price int,
  tax_type text not null default 'taxable' check (tax_type in ('taxable','exempt')),
  cert boolean not null default false,
  noob boolean not null default false,
  step smallint check (step between 1 and 4),
  level smallint check (level between 1 and 4),
  summary text not null default '',
  weeks int,
  months int,
  manual_end boolean not null default false,
  sort_order int not null default 0,
  -- 관리자 임시저장 중인 클래스는 고객 화면에 노출하지 않는다
  draft boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ── 클래스 상세 콘텐츠 (ClassDetail) — 1:1 ──
create table if not exists class_contents (
  class_id bigint primary key references classes(id) on delete cascade,
  detail jsonb not null default '{}'::jsonb,
  thumbnail_url text,
  banner_url text,
  detail_image_url text,
  vimeo_id text,
  updated_at timestamptz not null default now()
);

-- ── 회원 (auth.users 1:1, 아임웹 이관 회원은 user_id 없이 먼저 들어오고 첫 로그인 때 연결) ──
create table if not exists profiles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete set null,
  name text,
  phone text,
  email text,
  shop text,
  kakao_id text unique,
  imweb_member_id text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists profiles_phone_idx on profiles(phone);

-- ── 관리자 허용 목록 (카카오 로그인 관리자) — visual-auto hq_admin 은 로그인 때 visual-auto 쪽에서 확인 ──
create table if not exists admins (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete cascade,
  -- 아직 로그인 전인 사람을 미리 등록할 때 (첫 카카오 로그인 시 이메일로 연결)
  email text unique,
  name text not null,
  created_at timestamptz not null default now()
);

-- ── 신청(주문) ──
create sequence if not exists order_seq;
create table if not exists orders (
  id uuid primary key default gen_random_uuid(),
  order_no text not null unique,
  profile_id uuid not null references profiles(id),
  class_id bigint not null references classes(id),
  applicant jsonb not null,          -- { name, phone, email, shop }
  agreements jsonb not null default '{}'::jsonb,
  amount int not null,
  status text not null default '결제대기'
    check (status in ('결제대기','입금대기','수강확정','수강완료','취소신청','신청취소')),
  source text not null default 'web' check (source in ('web','imweb','manual')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists orders_profile_idx on orders(profile_id);
create index if not exists orders_class_idx on orders(class_id);

-- ── 결제 ──
create table if not exists payments (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references orders(id),
  toss_payment_key text unique,
  method text,
  amount int not null,
  tax_type text not null check (tax_type in ('taxable','exempt')),
  status text not null check (status in ('결제완료','부분환불','환불완료','입금대기','실패')),
  approved_no text,
  virtual_account jsonb,
  refund jsonb,
  invoice jsonb,
  raw jsonb,
  source text not null default 'toss' check (source in ('toss','imweb','manual')),
  paid_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists payments_order_idx on payments(order_id);

-- ── 온라인 수강권한 ──
create table if not exists enrollments (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references profiles(id),
  class_id bigint not null references classes(id),
  order_id uuid references orders(id),
  expires_at timestamptz,
  progress int not null default 0,      -- 0~100
  last_position_sec int not null default 0,
  created_at timestamptz not null default now(),
  unique (profile_id, class_id)
);

-- ── 개설 알림 신청 · 제휴 문의 · 알림톡 발송 기록 ──
create table if not exists waitlist_alerts (
  id uuid primary key default gen_random_uuid(),
  class_id bigint not null references classes(id) on delete cascade,
  profile_id uuid references profiles(id),
  phone text not null,
  notified_at timestamptz,
  created_at timestamptz not null default now(),
  unique (class_id, phone)
);

create table if not exists inquiries (
  id uuid primary key default gen_random_uuid(),
  kind text not null default 'partner',
  payload jsonb not null,
  handled boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists notification_log (
  id uuid primary key default gen_random_uuid(),
  kind text not null,          -- paid / vbank / d-3 / expire-30 / waitlist-open
  ref_id text not null,        -- order_id 등
  phone text,
  result jsonb,
  created_at timestamptz not null default now(),
  unique (kind, ref_id)
);

-- ── 신청 인원 계산 view: applied = applied_base + 유효 주문 (+ 개설 대기는 알림 신청 수) ──
create or replace view class_with_counts as
select c.*,
  c.applied_base
  + coalesce((select count(*) from orders o where o.class_id = c.id and o.status in ('입금대기','수강확정','수강완료')), 0)::int
  + case when c.type in ('waitlist','upcoming')
      then coalesce((select count(*) from waitlist_alerts w where w.class_id = c.id), 0)::int else 0 end
  as applied,
  cc.detail, cc.thumbnail_url, cc.banner_url, cc.detail_image_url
from classes c
left join class_contents cc on cc.class_id = c.id;

-- 주문번호 VA-YYYYMMDD-NNNN (KST 날짜)
create or replace function next_order_no() returns text language sql as $$
  select 'VA-' || to_char(now() at time zone 'Asia/Seoul', 'YYYYMMDD') || '-' || lpad((nextval('order_seq') % 10000)::text, 4, '0');
$$;

-- ── RLS ──
alter table instructors enable row level security;
alter table classes enable row level security;
alter table class_contents enable row level security;
alter table profiles enable row level security;
alter table admins enable row level security;
alter table orders enable row level security;
alter table payments enable row level security;
alter table enrollments enable row level security;
alter table waitlist_alerts enable row level security;
alter table inquiries enable row level security;
alter table notification_log enable row level security;

drop policy if exists "public read instructors" on instructors;
create policy "public read instructors" on instructors for select using (true);
drop policy if exists "public read classes" on classes;
create policy "public read classes" on classes for select using (not draft);
drop policy if exists "public read class_contents" on class_contents;
create policy "public read class_contents" on class_contents for select using (true);

drop policy if exists "own profile" on profiles;
create policy "own profile" on profiles for select using (user_id = auth.uid());
drop policy if exists "own orders" on orders;
create policy "own orders" on orders for select
  using (profile_id in (select id from profiles where user_id = auth.uid()));
drop policy if exists "own payments" on payments;
create policy "own payments" on payments for select
  using (order_id in (select o.id from orders o join profiles p on p.id = o.profile_id where p.user_id = auth.uid()));
drop policy if exists "own enrollments" on enrollments;
create policy "own enrollments" on enrollments for select
  using (profile_id in (select id from profiles where user_id = auth.uid()));
-- admins · waitlist_alerts · inquiries · notification_log: 정책 없음 = 서버(service role)만 접근

-- class_with_counts 는 소유자 권한 view 라 주문 수를 RLS 와 무관하게 센다 (개인정보 컬럼은 노출 안 함).
-- 앱은 서버에서 service role 로 읽고, 고객 화면은 draft = false 만 고른다.

-- ── 이미지 저장소 (공개 읽기, 업로드는 서버가 발급한 signed URL 로만) ──
insert into storage.buckets (id, name, public) values ('class-images', 'class-images', true)
on conflict (id) do nothing;

-- 시드·이관으로 id 를 직접 넣은 뒤 새 클래스 id 가 겹치지 않게 (scripts/seed.ts 가 호출)
create or replace function sync_class_id_seq() returns void language sql security definer as $$
  select setval(pg_get_serial_sequence('classes', 'id'), coalesce((select max(id) from classes), 1));
$$;
revoke execute on function sync_class_id_seq() from public, anon, authenticated;
